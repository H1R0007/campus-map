/**
 * Алиас узла в JSON-файле.
 *
 * Поддерживаются две формы: одиночное `name` (ранний формат) и массив
 * `names`. Загрузчик приводит обе к `names`.
 */
export interface AliasEntry {
  /** ID узла */
  id: string;

  /** Основная форма имени (устаревшее поле, сохранено для совместимости) */
  name?: string;

  /** Все формы имени */
  names?: string[];

  /**
   * Имена на других языках интерфейса: код языка (`en`) → имена.
   *
   * `names` — на языке данных, русском. Перевод необязателен ни для одного
   * узла: интерфейс без перевода показывает основное имя, а поиск находит
   * помещение по любому имени на любом языке. Номер аудитории вроде «А-305»
   * переводить не нужно — он совпадает с табличкой на двери.
   */
  translations?: Record<string, AliasTranslation>;

  /**
   * Вид места: туалет, столовая, гардероб — или любой вид, заведённый
   * разметчиком. По нему навигатор ищет ближайшее место нужного вида и
   * рисует значок. Необязателен: у аудитории его нет.
   *
   * Один на место. Задаётся в данных, а не угадывается по названию: «Буфет» и
   * «Кафе» — еда, а «Раздевалка» бассейна — не гардероб (запись 19).
   */
  category?: PlaceCategory;
}

/**
 * Вид места — id вида из каталога `place-kinds.json` (`PlaceKind` с
 * `place: true`).
 *
 * Прежде это был закрытый список из четырёх вариантов, и новый вид места
 * требовал правки навигатора. Теперь вид целиком описан в данных: название,
 * значок, слова поиска, быстрая кнопка (запись 44). Выхода среди видов нет:
 * выход — это вход, заведённый переходом, навигатор находит его сам.
 */
export type PlaceCategory = string;

/**
 * Перевод алиаса. Повторяет переводимые поля записи.
 */
export interface AliasTranslation {
  /** Формы имени на этом языке; первое считается основным. */
  names: string[];
}

/**
 * Результат поиска с ранжированием.
 */
export interface SearchSuggestion {
  /** Отображаемое имя */
  alias: string;

  /** ID узла */
  id: string;

  /** Внутренняя оценка релевантности (больше = лучше) */
  score: number;

  /**
   * Место нашлось по слову своей категории («туалет», «поесть»), а не по имени.
   * `alias` тогда — это слово, и показывать его как имя места нельзя.
   */
  viaCategory?: PlaceCategory;
}
