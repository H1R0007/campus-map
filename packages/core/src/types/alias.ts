/**
 * Алиас узла в JSON-файле.
 *
 * Поддерживаются две формы: одиночное `name` (ранний формат) и массив
 * `names`. Загрузчик приводит обе к `names`.
 */
export interface AliasEntry {
  /** ID узла */
  id: string;

  /** Основная форма имени (устаревшее поле, сохранено для совместимости) */
  name?: string;

  /** Все формы имени */
  names?: string[];

  /**
   * Имена на других языках интерфейса: код языка (`en`) → имена.
   *
   * `names` — на языке данных, русском. Перевод необязателен ни для одного
   * узла: интерфейс без перевода показывает основное имя, а поиск находит
   * помещение по любому имени на любом языке. Номер аудитории вроде «А-305»
   * переводить не нужно — он совпадает с табличкой на двери.
   */
  translations?: Record<string, AliasTranslation>;

  /**
   * Что это за место: туалет, еда, гардероб, выход. По категории навигатор
   * ищет ближайшее место нужного вида. Необязательна: у аудитории её нет.
   *
   * Одна на место. Задаётся в данных, а не угадывается по названию: «Буфет» и
   * «Кафе» — еда, а «Раздевалка» бассейна — не гардероб (запись 19).
   */
  category?: PlaceCategory;
}

/**
 * Категории мест, к ближайшему из которых ведут быстрые кнопки навигатора:
 *
 * - `toilet` — туалет;
 * - `food` — столовая, буфет, кафе;
 * - `cloakroom` — гардероб для верхней одежды;
 * - `exit` — выход из корпуса или с территории.
 *
 * Порядок — порядок кнопок в навигаторе.
 */
export const PLACE_CATEGORIES = ['toilet', 'food', 'cloakroom', 'exit'] as const;

export type PlaceCategory = (typeof PLACE_CATEGORIES)[number];

/** Является ли строка известной категорией места. */
export function isPlaceCategory(value: string): value is PlaceCategory {
  return (PLACE_CATEGORIES as readonly string[]).includes(value);
}

/**
 * Перевод алиаса. Повторяет переводимые поля записи.
 */
export interface AliasTranslation {
  /** Формы имени на этом языке; первое считается основным. */
  names: string[];
}

/**
 * Результат поиска с ранжированием.
 */
export interface SearchSuggestion {
  /** Отображаемое имя */
  alias: string;

  /** ID узла */
  id: string;

  /** Внутренняя оценка релевантности (больше = лучше) */
  score: number;
}
