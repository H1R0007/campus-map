import type { TransitionType } from './transition.js';

/**
 * Параметры поиска пути.
 *
 * Все флаги по умолчанию разрешены (`?? true`), поэтому вызов без опций
 * ищет кратчайший путь без ограничений.
 */
export interface PathfindingOptions {
  /** Разрешены ли лестницы */
  allowStairs?: boolean;

  /** Разрешены ли лифты */
  allowLift?: boolean;

  /** Разрешены ли переходы между корпусами */
  allowBridge?: boolean;

  /** Разрешены ли входы/выходы (кампус <-> корпус) */
  allowEntrance?: boolean;

  /** Предпочитать лифт лестнице */
  preferLift?: boolean;

  /** Ограничение итераций — защита от зацикливания на битых данных */
  maxIterations?: number;
}

/**
 * Опции поиска пути по умолчанию: все способы перемещения разрешены,
 * предпочтение лифту не отдаётся.
 *
 * Живут в ядре, потому что одинаковы для навигатора и редактора: оба
 * приложения держали свой экземпляр этого объекта, и редактор — дважды
 * (начальное состояние и сброс при загрузке данных).
 *
 * Тип `Required<…>` здесь важен: он заставляет перечислить **все** поля.
 * Раньше в этом объекте не было `maxIterations`, а настоящее значение по
 * умолчанию подставлялось отдельно в поиске — то есть существовало два
 * независимых источника истины об одном и том же, и вызывающая сторона,
 * разложившая этот объект, получала не тот набор, с которым работает A*.
 */
export const DEFAULT_PATHFINDING_OPTIONS: Readonly<Required<PathfindingOptions>> = Object.freeze({
  allowStairs: true,
  allowLift: true,
  allowBridge: true,
  allowEntrance: true,
  preferLift: false,

  // Защита от зацикливания на битых данных. Порог с большим запасом: на
  // связном графе кампуса реальный поиск укладывается в сотни извлечений.
  maxIterations: 50_000,
});

/**
 * Один шаг маршрута.
 */
export interface PathSegment {
  /** ID узла, из которого идёт шаг */
  fromNode: string;

  /** ID узла, в который идёт шаг */
  toNode: string;

  /** Тип перехода (null для обычного ребра на этаже) */
  transitionType: TransitionType | null;

  /**
   * Стоимость шага в модели поиска.
   *
   * Считается той же функцией, что и стоимость ребра при поиске, поэтому
   * сумма стоимостей всех шагов всегда равна `PathResult.cost` — включая
   * режим `preferLift`, который меняет стоимость лестниц.
   */
  cost: number;

  /**
   * Длина шага по плану (горизонтальная проекция), метры.
   *
   * `null` в пиксельном режиме. Сумма по шагам равна `PathResult.distanceMeters`.
   */
  distanceMeters: number | null;

  /**
   * Время шага, секунды: ходьба, подъём, ожидание лифта при посадке, проход входа.
   *
   * `null` в пиксельном режиме. Сумма по шагам равна `PathResult.durationSeconds`:
   * инструкции маршрута показывают время участков, и оно обязано сходиться с
   * итогом в карточке маршрута.
   */
  durationSeconds: number | null;
}

/**
 * Почему путь не найден.
 *
 * - `unknown-start`, `unknown-end` — точки нет в графе;
 * - `unreachable` — точки не связаны при заданных ограничениях;
 * - `iteration-limit` — поиск остановлен защитой от зацикливания.
 */
export type PathFailureReason = 'unknown-start' | 'unknown-end' | 'unreachable' | 'iteration-limit';

/**
 * Результат поиска пути.
 */
export interface PathResult {
  /** Найден ли путь */
  found: boolean;

  /** Список ID узлов пути (от старта к финишу) */
  path: string[];

  /**
   * Стоимость пути — то, что минимизировал поиск.
   *
   * В метрическом режиме это секунды **с учётом предпочтений**: при
   * `preferLift` лестница здесь дороже, чем в жизни, поэтому время в пути —
   * отдельное поле. В пиксельном режиме — условные единицы, которые нельзя
   * показывать ни как расстояние, ни как время. Раньше это поле называлось
   * `totalDistance`, и навигатор делил его на выдуманную скорость.
   */
  cost: number;

  /**
   * Длина пути по плану (горизонтальная проекция), метры.
   *
   * `null` в пиксельном режиме и если путь не найден.
   */
  distanceMeters: number | null;

  /**
   * Время в пути, секунды: ходьба, подъёмы, ожидание лифта, проход входов.
   *
   * Физика найденного пути — от предпочтений не зависит. `null` в пиксельном
   * режиме и если путь не найден: выдуманное число хуже отсутствующего.
   */
  durationSeconds: number | null;

  /** Разбивка по шагам (только если путь найден) */
  segments?: PathSegment[];

  /**
   * Почему путь не найден (только если не найден).
   *
   * Интерфейс показывает текст на своём языке по этому коду.
   */
  reason?: PathFailureReason;

  /**
   * Описание неудачи для разработчика — на русском и с id узлов.
   *
   * Студенту не показывается: навигатор двуязычный, а текст ядра — нет.
   */
  error?: string;
}

/**
 * Основной путь вместе с альтернативами.
 */
export interface MultiPathResult {
  /** Основной (кратчайший) путь */
  primary: PathResult;

  /** Альтернативные пути, отсортированные по возрастанию стоимости */
  alternatives: PathResult[];
}
