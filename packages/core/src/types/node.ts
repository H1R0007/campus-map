/**
 * Узел навигационного графа.
 * Представляет точку на карте: комнату, коридор, лестницу и т.д.
 */
export interface MapNode {
  /** Уникальный идентификатор узла */
  id: string;

  /** X-координата в пикселях карты */
  x: number;

  /** Y-координата в пикселях карты */
  y: number;

  /** Номер этажа (0 = территория кампуса) */
  floor: number;

  /** ID корпуса ("CAMPUS" для территории кампуса) */
  building: string;

  /** Является ли узел точкой перехода между этажами/корпусами */
  isPortal: boolean;

  /** ID соседних узлов на том же этаже */
  neighbors: string[];

  /**
   * Служебная заметка разметчика.
   *
   * Не влияет на маршрутизацию и не показывается студентам — это рабочий
   * инструмент команды, которая размечает планы. Полезен на этапе переноса
   * официальных данных: можно помечать спорные места («уточнить у
   * коменданта», «дверь закрыта после 18:00», «геометрия приблизительная»).
   */
  comment?: string;

  /**
   * Ориентир — заметная вещь у точки, по которой место узнают на ходу:
   * «Кофейный автомат». Маршрут через такую точку получает свой шаг: «У
   * кофейного автомата поверните налево» (запись 85).
   */
  landmark?: Landmark;

  /**
   * Фото точки: дверь помещения, вход снаружи, сам ориентир. Первое —
   * главное: его навигатор показывает в карточке и на шаге маршрута.
   */
  photos?: PointPhoto[];
}

/**
 * Ориентир у точки.
 *
 * Название и фраза хранятся порознь, потому что нужны в разных местах.
 * Название — именительный падеж, как на подписи: им ориентир подписан на
 * карте и под фото. Фраза — как он звучит в шаге: «у кофейного автомата».
 * Произвольное имя в падеж не поставить ни в одном языке (запись 11), поэтому
 * фразу составляет редактор, а разметчик видит и правит её; навигатор её
 * только читает.
 */
export interface Landmark {
  /** «Кофейный автомат». */
  name: string;

  /**
   * «у кофейного автомата». Без фразы шаг говорит действие, а ориентир —
   * отдельно, названием.
   */
  at?: string;

  /** Перевод на другие языки интерфейса: код языка (`en`) → название и фраза. */
  translations?: Record<string, LandmarkTranslation>;
}

/**
 * Наибольшая длина названия и фразы ориентира, знаков. Ориентир — короткая
 * подпись, которую читают на ходу; длинное описание — повод для заметки
 * разметчика, а не для шага маршрута.
 */
export const MAX_LANDMARK_LENGTH = 80;

/** Перевод ориентира: «Coffee machine», «at the coffee machine». */
export interface LandmarkTranslation {
  name: string;
  at?: string;
}

/**
 * Фото точки.
 *
 * Файл называется отпечатком содержимого — первыми 16 знаками SHA-256 — и
 * лежит в каталоге фото рядом с уменьшенной копией (`photoPath` в
 * `dataset/paths.ts`). Имя по содержимому: телефон хранит фото и не
 * перепроверяет его, поэтому заменённое фото обязано получить новое имя, иначе
 * на экране осталось бы старое.
 */
export interface PointPhoto {
  /** `3f2a9c1b7d4e8a01.webp` — отпечаток и формат. */
  file: string;

  /** Размер полного фото в пикселях: место под фото известно до загрузки. */
  width: number;
  height: number;
}

/**
 * Узел в том виде, в каком он лежит в `graph.json`.
 *
 * `building` и `floor` экспортом не записываются: их источник истины —
 * расположение файла (`buildings/<id>/floors/<n>/graph.json`), а для
 * кампуса — `campus/graph.json`. Поля оставлены в типе только для того,
 * чтобы загрузчик мог обнаружить расхождение и предупредить о нём;
 * значение всегда берётся из пути.
 */
export interface MapNodeData {
  id: string;
  x: number;
  y: number;
  isPortal?: boolean;
  neighbors?: string[];
  comment?: string;
  landmark?: Landmark;
  photos?: PointPhoto[];
  /** @deprecated определяется путём файла, см. описание типа */
  floor?: number;
  /** @deprecated определяется путём файла, см. описание типа */
  building?: string;
}

