import type { PlaceCategory } from './alias.js';
import type { TransitionType } from './transition.js';

/**
 * Вид точки — заготовка разметчика.
 *
 * Отвечает на вопросы, которые редактор задаёт каждой новой точке: как её
 * назвать, точка ли это перехода, какого типа переход, соединять ли с
 * соседями, какой вид места показать навигатору. Один щелчок кистью
 * подставляет всё это разом.
 *
 * Виды — данные, а не код: разметчик заводит свои прямо в редакторе, и они
 * едут в git вместе с разметкой. Новых полей у узлов и названий при этом не
 * появляется — вид лишь заполняет те, что уже есть (запись 40).
 *
 * Навигатор виды не читает: значок и быстрые кнопки у него свои, и новый вид
 * их не добавляет. Дотянуться до навигатора можно полем `category` — это один
 * из четырёх видов мест, которые он знает.
 */
export interface PlaceKind {
  /** Имя в файле: латиницей, без пробелов. */
  id: string;

  /** Как вид называется человеку: «Аудитория», «Лестница». */
  name: string;

  /** Значок редактора; неизвестное имя — обычная точка. */
  icon?: string;

  /**
   * Цвет точки в редакторе — имя из палитры редактора, а не код цвета:
   * цвета объявлены токенами в одном месте.
   */
  color?: string;

  /**
   * Шаблон названия. `{корпус}` и `{этаж}` подставляет редактор, `{номер}` —
   * место, куда встанет курсор. Без шаблона название не предлагается.
   */
  namePattern?: string;

  /** Точка смены этажа или корпуса: лестница, лифт, вход. */
  isPortal?: boolean;

  /** Каким переходом связывать точки этого вида на разных планах. */
  transition?: TransitionType;

  /** Ставить точку сразу на всех этажах корпуса и связывать переходами. */
  stack?: boolean;

  /** Соединять новую точку с ближайшей точкой плана. */
  connect?: boolean;

  /** Вид места для навигатора: туалет, еда, гардероб, выход. */
  category?: PlaceCategory;
}
