/**
 * Вид точки — заготовка разметчика для мест: коридор, помещение, туалет,
 * столовая, гардероб и всё, что разметчик заведёт сам.
 *
 * Вид с `place: true` — место быстрого поиска: его id становится видом места
 * (`category`) у поставленных точек, а навигатор берёт из каталога всё, что
 * нужно студенту, — название на обоих языках, значок, слова поиска, быструю
 * кнопку. Новый вид ничем не отличается от встроенного (запись 44).
 *
 * Отвечает на вопросы, которые редактор задаёт каждой новой точке: как её
 * назвать, соединять ли с соседями, какой вид места показать навигатору.
 * Один щелчок кистью подставляет всё это разом.
 *
 * Переходов здесь нет: лестница, лифт, вход и переход между корпусами — это
 * смена этажа или корпуса, у них свой инструмент «Переход» со своей логикой.
 *
 * Виды — данные, а не код: разметчик заводит свои прямо в редакторе, и они
 * едут в git вместе с разметкой. Новых полей у узлов и названий при этом не
 * появляется — вид лишь заполняет те, что уже есть (запись 40).
 *
 * Навигатор виды не читает: значок и быстрые кнопки у него свои, и новый вид
 * их не добавляет. Дотянуться до навигатора можно полем `category` — это один
 * из четырёх видов мест, которые он знает.
 */
export interface PlaceKind {
  /** Имя в файле: латиницей, без пробелов. */
  id: string;

  /** Как вид называется человеку: «Столовая», «Медпункт». */
  name: string;

  /** Название по-английски — для английского интерфейса навигатора. */
  nameEn?: string;

  /**
   * Какой значок выбран: `tabler:<имя>` из набора редактора, `custom` —
   * загруженный разметчиком, прежние имена значков редактора — как есть.
   */
  icon?: string;

  /**
   * Сама картинка значка — адресом `data:` (SVG или PNG). По ней значок
   * рисуют и редактор, и навигатор: навигатору не нужна библиотека значков.
   */
  iconImage?: string;

  /**
   * Цвет точки в редакторе — имя из палитры редактора, а не код цвета:
   * цвета объявлены токенами в одном месте.
   */
  color?: string;

  /**
   * Шаблон названия. `{корпус}` и `{этаж}` подставляет редактор, `{номер}` —
   * место, куда встанет курсор. Без шаблона название не предлагается.
   */
  namePattern?: string;

  /**
   * Место быстрого поиска: точки вида получают вид места, навигатор находит
   * ближайшее такое место и показывает значок. У коридора и помещения — нет.
   */
  place?: boolean;

  /** Быстрая кнопка в навигаторе («Рядом»); порядок кнопок — порядок каталога. */
  quick?: boolean;

  /**
   * Слова, по которым ищут все места вида: «поесть», «столовка», «canteen».
   * Название вида ищется и так.
   */
  searchTerms?: string[];

  /** Соединять новую точку с ближайшей точкой плана. */
  connect?: boolean;

  /**
   * Вести линию: каждая следующая точка соединяется с предыдущей, как при
   * рисовании ломаной. Так размечают коридоры.
   */
  chain?: boolean;

}
