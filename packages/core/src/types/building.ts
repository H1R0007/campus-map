/**
 * Метаданные этажа.
 * Пути относительны к каталогу этажа: `data/buildings/<id>/floors/<n>/`.
 */
export interface FloorMeta {
  /** Номер этажа */
  floor: number;

  /** Путь к растровой карте этажа */
  mapPath: string;

  /** Путь к графу этажа */
  graphPath: string;
}

/**
 * Метаданные корпуса.
 *
 * Намеренно не содержит `bounds`: поле существовало в формате, грузилось и
 * выгружалось, но нигде не читалось, а способа задать его в редакторе не
 * было. Возвращать его нужно вместе с фичей «кликабельные корпуса на карте
 * кампуса» и инструментом разметки в редакторе — иначе это снова мёртвые
 * данные, которые кто-то обязан заполнить вручную.
 */
export interface BuildingMeta {
  /** Уникальный ID корпуса */
  id: string;

  /** Отображаемое имя */
  name: string;

  /** Список этажей */
  floors: FloorMeta[];
}

/**
 * Метаданные кампуса.
 */
export interface CampusMeta {
  /** Список ID корпусов кампуса */
  buildings: { id: string; name?: string }[];

  /**
   * Размер карты кампуса в пикселях.
   *
   * Используется только как резервное значение, если картинку не удалось
   * загрузить: реальный размер всегда берётся из самого изображения.
   */
  mapSize: {
    width: number;
    height: number;
  };
}
