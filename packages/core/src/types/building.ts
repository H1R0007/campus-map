/**
 * Размер растрового плана в пикселях.
 */
export interface MapSize {
  width: number;
  height: number;
}

/**
 * Привязка растрового плана к территории кампуса.
 *
 * Точка плана переводится в пространство кампуса так:
 *
 *     world = originMeters + R(rotationDeg) · (metersPerPixel · pixel)
 *
 * `pixel` — координаты на изображении плана (ось y вниз), `R` — поворот по
 * часовой стрелке так, как его видит человек на экране. Пространство кампуса —
 * план территории, переведённый в метры: начало в его левом верхнем углу, ось
 * y тоже вниз. `originMeters` — где на территории лежит левый верхний угол
 * этого плана, поворот идёт вокруг этого угла.
 *
 * Только подобие — равномерный масштаб, поворот и сдвиг. Скоса,
 * неравномерного масштаба и зеркалирования в формате нет намеренно: с ними
 * метр на плане зависел бы от направления, а подложку нельзя было бы
 * нарисовать одним поворотом и масштабом.
 *
 * Значений по умолчанию нет ни у одного поля: подставленные `metersPerPixel = 1`
 * или нулевой сдвиг молча сложили бы все корпуса в начало координат. Полноту
 * привязки проверяет `createCampusProjection`.
 */
export interface PlanPlacement {
  /** Метров в одном пикселе плана. */
  metersPerPixel?: number;

  /** Положение левого верхнего угла плана на территории, метры. */
  originMeters?: { x: number; y: number };

  /** Поворот плана относительно территории, градусы по часовой стрелке. */
  rotationDeg?: number;
}

/**
 * Привязка корпуса — значения по умолчанию для всех его этажей.
 *
 * Отметка этажа с номером `n`:
 *
 *     baseElevationMeters + (n − 1) · floorHeightMeters
 *
 * То есть `baseElevationMeters` — отметка пола **первого** этажа над уровнем
 * территории. Формула считает по номеру этажа, а не по порядку в списке:
 * добавление этажа в данные не должно сдвигать высоты остальных. Там, где
 * номер с высотой не согласуется (нумерация без нулевого этажа, антресоль,
 * этаж другой высоты), задаётся `FloorMeta.elevationMeters`.
 */
export interface BuildingPlacement extends PlanPlacement {
  /** Отметка пола первого этажа над уровнем территории, метры. */
  baseElevationMeters?: number;

  /** Высота этажа, метры. */
  floorHeightMeters?: number;
}

/**
 * Метаданные этажа.
 *
 * Путей к файлам здесь нет намеренно: раскладка этажа фиксирована
 * (`buildings/<id>/floors/<n>/graph.json` и `map.png`, см. `dataset/paths.ts`).
 * Раньше формат содержал `mapPath` и `graphPath` — они грузились и
 * выгружались экспортом, но ни один читатель их не использовал: адреса всегда
 * собирались константами. Разметчик, вписавший туда другое имя файла, получал
 * молчаливый 404. Та же история, что с удалённым `BuildingMeta.bounds`.
 */
export interface FloorMeta {
  /** Номер этажа */
  floor: number;

  /**
   * Размер плана этажа в пикселях.
   *
   * Настоящий размер навигатор всё равно берёт из самого изображения, а это
   * значение нужно до его загрузки: без него план сначала показывается в
   * резервных габаритах, а после загрузки карта перескакивает на настоящие.
   * Устаревший размер маршрут не ломает — возвращается только этот скачок.
   */
  mapSize?: MapSize;

  /**
   * Привязка плана этажа — поверх привязки корпуса.
   *
   * Нужна, когда планы одного корпуса отсканированы в разном масштабе или
   * обрезаны по-разному. Незаданные поля берутся у корпуса. Отметки этажа
   * здесь нет: её задаёт `elevationMeters`, и второй способ сказать то же
   * самое был бы вторым источником истины.
   */
  placement?: PlanPlacement;

  /** Отметка пола этажа над уровнем территории, метры. Важнее формулы корпуса. */
  elevationMeters?: number;
}

/**
 * Метаданные корпуса.
 *
 * Намеренно не содержит `bounds`: поле существовало в формате, грузилось и
 * выгружалось, но нигде не читалось, а способа задать его в редакторе не
 * было. Возвращать его нужно вместе с фичей «кликабельные корпуса на карте
 * кампуса» и инструментом разметки в редакторе — иначе это снова мёртвые
 * данные, которые кто-то обязан заполнить вручную.
 */
export interface BuildingMeta {
  /** Уникальный ID корпуса */
  id: string;

  /** Отображаемое имя */
  name: string;

  /**
   * Этаж, который открывается при выборе корпуса на карте кампуса, — обычно
   * этаж главного входа.
   *
   * Необязателен: без него навигатор выбирает низший надземный этаж. Но
   * нумерация этажей в вузах разная, и по номерам её не угадать — в
   * европейской «0» как раз этаж входа. Загрузчик принимает только номер
   * одного из объявленных этажей.
   */
  entranceFloor?: number;

  /** Привязка планов корпуса к территории кампуса. */
  placement?: BuildingPlacement;

  /**
   * Имя корпуса на других языках интерфейса: код языка (`en`) → перевод.
   *
   * `name` — на языке данных, русском; без перевода интерфейс показывает его.
   */
  translations?: Record<string, BuildingTranslation>;

  /** Список этажей */
  floors: FloorMeta[];
}

/**
 * Перевод метаданных корпуса. Повторяет переводимые поля записи.
 */
export interface BuildingTranslation {
  name: string;
}

/**
 * Метаданные кампуса.
 */
export interface CampusMeta {
  /** Список ID корпусов кампуса */
  buildings: { id: string; name?: string }[];

  /**
   * Размер карты кампуса в пикселях.
   *
   * Смысл тот же, что у `FloorMeta.mapSize`: границы плана до загрузки
   * изображения. Реальный размер всегда берётся из самой картинки.
   */
  mapSize: MapSize;

  /**
   * Масштаб плана территории: метров в одном пикселе.
   *
   * Задаёт само пространство кампуса, в котором привязаны корпуса. Без него
   * датасет работает в пиксельном режиме, даже если все корпуса привязаны.
   */
  metersPerPixel?: number;
}
