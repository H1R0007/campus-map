/**
 * Размер растрового плана в пикселях.
 */
export interface MapSize {
  width: number;
  height: number;
}

/**
 * Метаданные этажа.
 *
 * Путей к файлам здесь нет намеренно: раскладка этажа фиксирована
 * (`buildings/<id>/floors/<n>/graph.json` и `map.png`, см. `dataset/paths.ts`).
 * Раньше формат содержал `mapPath` и `graphPath` — они грузились и
 * выгружались экспортом, но ни один читатель их не использовал: адреса всегда
 * собирались константами. Разметчик, вписавший туда другое имя файла, получал
 * молчаливый 404. Та же история, что с удалённым `BuildingMeta.bounds`.
 */
export interface FloorMeta {
  /** Номер этажа */
  floor: number;

  /**
   * Размер плана этажа в пикселях.
   *
   * Настоящий размер навигатор всё равно берёт из самого изображения, а это
   * значение нужно до его загрузки: без него план сначала показывается в
   * резервных габаритах, а после загрузки карта перескакивает на настоящие.
   * Устаревший размер маршрут не ломает — возвращается только этот скачок.
   */
  mapSize?: MapSize;
}

/**
 * Метаданные корпуса.
 *
 * Намеренно не содержит `bounds`: поле существовало в формате, грузилось и
 * выгружалось, но нигде не читалось, а способа задать его в редакторе не
 * было. Возвращать его нужно вместе с фичей «кликабельные корпуса на карте
 * кампуса» и инструментом разметки в редакторе — иначе это снова мёртвые
 * данные, которые кто-то обязан заполнить вручную.
 */
export interface BuildingMeta {
  /** Уникальный ID корпуса */
  id: string;

  /** Отображаемое имя */
  name: string;

  /** Список этажей */
  floors: FloorMeta[];
}

/**
 * Метаданные кампуса.
 */
export interface CampusMeta {
  /** Список ID корпусов кампуса */
  buildings: { id: string; name?: string }[];

  /**
   * Размер карты кампуса в пикселях.
   *
   * Смысл тот же, что у `FloorMeta.mapSize`: границы плана до загрузки
   * изображения. Реальный размер всегда берётся из самой картинки.
   */
  mapSize: MapSize;
}
