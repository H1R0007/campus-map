/**
 * Примитивы геометрии и идентификации рёбер.
 *
 * Вынесены в отдельный модуль, потому что используются и графом, и
 * поиском пути, и автофиксом, и валидацией. Раньше формула ключа ребра
 * `[a, b].sort().join('|')` была продублирована в шести местах.
 */

/**
 * Евклидово расстояние между двумя точками в пиксельной системе карты.
 *
 * Имеет смысл только для точек **одного** плана: у каждого плана своя система
 * координат. Поэтому это стоимость ребра внутри этажа в пиксельной модели, но
 * не эвристика поиска — оценка остатка между этажами по пикселям переоценивала
 * бы его (запись 6 в `DECISIONS.md`). Эвристика живёт в
 * `pathfinding/costModel.ts` и считается в метрах пространства кампуса.
 */
export function distance(
  a: { x: number; y: number },
  b: { x: number; y: number }
): number {
  const dx = a.x - b.x;
  const dy = a.y - b.y;
  return Math.sqrt(dx * dx + dy * dy);
}

/**
 * Канонический ключ ненаправленного ребра.
 *
 * Рёбра в графе ненаправленные, поэтому `(a, b)` и `(b, a)` обязаны давать
 * один и тот же ключ. Порядок компонентов фиксируется сортировкой.
 */
export function edgeKey(nodeA: string, nodeB: string): string {
  return nodeA < nodeB ? `${nodeA}|${nodeB}` : `${nodeB}|${nodeA}`;
}

/**
 * Ключ связки «корпус + этаж».
 *
 * Используется для индексации узлов: выборка узлов этажа должна быть O(1),
 * а не O(N) по всему графу — корпусов и этажей в реальных данных будет
 * на порядок больше, чем в тестовом наборе.
 */
export function floorKey(building: string, floor: number): string {
  return `${building}#${floor}`;
}
