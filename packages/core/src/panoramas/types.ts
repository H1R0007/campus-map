/**
 * Панорамы 360° в точках графа (запись 90 в `DECISIONS.md`).
 *
 * Описание панорам лежит в данных (`panoramas.json`), а сами снимки — вне
 * git и вне `data/`: они тяжёлые, а на снимках вуза может быть то, что
 * публиковать нельзя. Здесь — только то, что нужно, чтобы показать снимок и
 * расставить на нём стрелки: какой узел, какой файл и как снимок повёрнут.
 */

/**
 * Панорама в том виде, в каком она лежит в `panoramas.json`.
 */
export interface PanoramaData {
  /** Узел графа, в котором стояла камера. */
  node: string;

  /**
   * Имя файла в хранилище панорам — относительно его корня, латиницей:
   * `building_a/1/hall.jpg`. Хранилище задаёт развёртывание, не данные.
   */
  file: string;

  /**
   * Куда смотрит середина снимка: градусы по часовой стрелке от верха плана
   * этажа этого узла (0 — вверх по плану, 90 — вправо). `null` или поля нет —
   * направление ещё не выставлено: снимок показывается без стрелок.
   */
  heading?: number | null;

  /** Когда снято: `ГГГГ-ММ` или `ГГГГ-ММ-ДД`. */
  takenAt?: string;

  /** Ручная правка стрелок; без неё стрелки выводятся из графа. */
  links?: {
    /** Узлы соседних панорам, стрелки к которым не показывать. */
    hide?: string[];

    /**
     * Направление стрелки к узлу соседней панорамы, градусы от верха плана.
     * Нужно там, где граф направления не знает: лестница или лифт стоят в
     * одной точке плана на всех этажах.
     */
    headings?: Record<string, number>;
  };
}

/** Файл `panoramas.json`. */
export interface PanoramasFileData {
  panoramas: PanoramaData[];
}

/**
 * Панорама после разбора: поля проверены, углы приведены к [0, 360).
 */
export interface Panorama {
  node: string;
  file: string;

  /** Куда смотрит середина снимка, градусы от верха плана; `null` — не выставлено. */
  heading: number | null;

  takenAt: string | null;

  /** Стрелки, которые не показывать: узлы соседних панорам. */
  hiddenLinks: ReadonlySet<string>;

  /** Направления стрелок, заданные вручную: узел соседней панорамы → градусы. */
  linkHeadings: ReadonlyMap<string, number>;
}
