import { describe, expect, it } from 'vitest';
import { englishAt, russianAt } from '../src/utils/landmarkPhrase';

/**
 * Фраза ориентира из названия (запись 87). Это догадка — разметчик видит
 * готовое предложение и правит, — но для частых в вузе ориентиров она обязана
 * быть верной.
 */
describe('russianAt', () => {
  const cases: Array<[string, string]> = [
    ['Кофейный автомат', 'у кофейного автомата'],
    ['Турникеты', 'у турникетов'],
    ['Стеклянная дверь', 'у стеклянной двери'],
    ['Двери', 'у дверей'],
    ['Доска объявлений', 'у доски объявлений'],
    ['Лестница', 'у лестницы'],
    ['Гардероб', 'у гардероба'],
    ['Окно выдачи', 'у окна выдачи'],
    ['Стенд с расписанием', 'у стенда с расписанием'],
    ['Большой глобус', 'у большого глобуса'],
    ['Синий диван', 'у синего дивана'],
    ['Высокий шкаф', 'у высокого шкафа'],
    ['Музей', 'у музея'],
    ['Здание', 'у здания'],
    ['Аудитория', 'у аудитории'],
    ['Указатель', 'у указателя'],
    ['Огнетушитель', 'у огнетушителя'],
    ['Кафе', 'у кафе'],
    ['МФЦ', 'у МФЦ'],
    ['Стенд «Наука»', 'у стенда «Наука»'],
    ['Пункт охраны', 'у пункта охраны'],
    ['  Банкомат ', 'у банкомата'],
  ];

  for (const [name, phrase] of cases) {
    it(`«${name}» → «${phrase}»`, () => {
      expect(russianAt(name)).toBe(phrase);
    });
  }

  it('номер не склоняется и не теряет заглавную', () => {
    expect(russianAt('А-305')).toBe('у А-305');
  });

  it('пустое название — фразы нет', () => {
    expect(russianAt('   ')).toBeNull();
  });
});

describe('englishAt', () => {
  it('at the + название со строчной; сокращение и «the» — как есть', () => {
    expect(englishAt('Coffee machine')).toBe('at the coffee machine');
    expect(englishAt('ATM')).toBe('at the ATM');
    expect(englishAt('The main stairs')).toBe('at the main stairs');
    expect(englishAt('')).toBeNull();
  });
});
