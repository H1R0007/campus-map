/**
 * Щелчок, который браузер присылает в конце перетаскивания.
 *
 * Узел под курсором едет вместе с мышью, и отпускание кнопки часто
 * приходится уже на карту: браузер шлёт `click` общему предку — контейнеру
 * карты, и щелчок «по пустому месту» снимал бы выделение только что
 * перетащенных узлов. Перетаскивание по окончании просит пропустить ближайший
 * такой щелчок.
 */

let suppressUntil = 0;

/** Пропустить щелчок по карте, пришедший в ближайшие `ms` миллисекунд. */
export function suppressNextMapClick(ms = 400): void {
  suppressUntil = performance.now() + ms;
}

/** Нужно ли пропустить этот щелчок по карте. */
export function isMapClickSuppressed(): boolean {
  return performance.now() < suppressUntil;
}
