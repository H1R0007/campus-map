import type React from 'react';
import { createPortal } from 'react-dom';

/**
 * Слой окон (запись 68): окно рисуется поверх всего редактора, где бы его ни
 * открыли, — из дерева, из карты, из правой колонки.
 *
 * Окно, открытое изнутри карты («Добавить этаж вручную» у корпуса без
 * этажей), жило в её слое: когда карты рядом, вторая карта закрывала
 * половину окна. Окно всегда нужно довести до конца, поэтому оно выносится в
 * конец страницы, над всеми картами и панелями.
 *
 * События из окна по-прежнему всплывают по дереву React к тем, кто его
 * открыл: обработчики нажатий на карту проверяют, что нажали именно по ней.
 */
export const DialogLayer: React.FC<{ children: React.ReactNode }> = ({ children }) => createPortal(children, document.body);
