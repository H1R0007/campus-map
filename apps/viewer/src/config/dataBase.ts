import { DATA_ROOT } from '@campus-map/core';

/**
 * Базовый URL каталога данных.
 *
 * Ядро принимает `baseUrl` во всех URL-хелперах (`datasetUrl`, `floorMapUrl`,
 * `campusMapUrl`, `createHttpDatasetSource`), но по умолчанию подставляет
 * абсолютный `/data`. Пока приложение живёт в корне домена, разницы нет; при
 * развёртывании в подкаталоге (`https://вуз.рф/map/`) абсолютный путь уводит
 * все запросы датасета в корень, где их никто не раздаёт.
 *
 * `import.meta.env.BASE_URL` Vite выводит из `base` в `vite.config.ts` и
 * всегда завершает слэшем, поэтому склейка безопасна.
 *
 * Значение считается один раз на модуль: оно постоянно в пределах сборки, а
 * пересчёт на каждый вызов только плодил бы строки.
 */
export const DATA_BASE_URL = `${import.meta.env.BASE_URL}${DATA_ROOT}`;
